def ts(x):
    ms = int(round(x * 1000)); h, ms = divmod(ms, 3600000); m, ms = divmod(ms, 60000); s, ms = divmod(ms, 1000)
    return f'{h:02d}:{m:02d}:{s:02d},{ms:03d}'
def chunks(text, maxc=84):
    words = text.split(); out = []; cur = ''
    for w in words:
        if len(cur) + len(w) + 1 > maxc and cur: out.append(cur); cur = w
        else: cur = (cur + ' ' + w).strip()
    if cur: out.append(cur)
    # balance: avoid tiny last chunk
    if len(out) > 1 and len(out[-1]) < 20:
        last = out.pop(); out[-1] += ' ' + last
    return out
def srt(lang):
    lines = []; n = 1
    for st, en, e, r in subs:
        text = e if lang == 'en' else r
        parts = chunks(text); tot = sum(len(p) for p in parts); t = st
        for p in parts:
            d = (en - st) * len(p) / tot
            body = '\n'.join(textwrap.wrap(p, 44 if lang == 'en' else 46))
            lines.append(f'{n}\n{ts(t)} --> {ts(min(t + d, en) + 0.15)}\n{body}\n'); n += 1; t += d
    return '\n'.join(lines)
