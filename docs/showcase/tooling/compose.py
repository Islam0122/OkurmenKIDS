def probe(f):
    return float(subprocess.check_output(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).decode())

def clip_window(name, a_url, b_url):
    marks = json.load(open(f'rec/out/{name}.marks.json'))
    L = probe(f'rec/out/{name}.mp4')
    def first(u): return next(i for i, m in enumerate(marks) if m['url'] == u)
    ia = 0 if a_url is None else first(a_url)
    ib = None if b_url is None else first(b_url)
    a = 0.0 if ia == 0 else marks[ia]['t']
    b = L if ib is None else marks[ib]['t']
    inner = [m for m in marks[ia:(ib if ib is not None else len(marks))]]
    # merge consecutive same-url marks
    segs = []
    for m in inner:
        if segs and segs[-1]['url'] == m['url']: continue
        segs.append(dict(t=max(0.0, m['t'] - a), url=m['url']))
    if segs: segs[0]['t'] = 0.0
    return a, b, segs

