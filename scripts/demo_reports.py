class Director:
    """Smooth pointer movement + pauses, so every action is visible on video."""

    def __init__(self, page: Page, voice_durations: dict[str, float] | None = None):
        self.page = page
        self.x, self.y = VIEWPORT["width"] * 0.5, VIEWPORT["height"] * 0.55
        self.started = time.monotonic()
        self.marks: list[tuple[str, float]] = []
        self.voice_durations = voice_durations or {}
        self.voice_starts: dict[str, float] = {}

    def now(self) -> float:
        return time.monotonic() - self.started

    def mark(self, scene: str, line: str | None = None) -> None:
        """Start of a scene; `line` — its narration line starts here too."""
        self.marks.append((scene, self.now()))
        if line and line in self.voice_durations:
            self.voice_starts[line] = self.now()
        print(f"  [{self.marks[-1][1]:5.1f}s] {scene}")

    def hold(self, line: str, *, gap: float = 0.3) -> None:
        """Wait until the narration line has been spoken (the scene never outruns the voice)."""
        if line not in self.voice_starts:
            return
        remaining = self.voice_starts[line] + self.voice_durations[line] + gap - self.now()
        if remaining > 0:
            self.pause(remaining)

    def pause(self, seconds: float) -> None:
        self.page.wait_for_timeout(int(seconds * 1000))

    def move(self, target: Locator, *, steps: int = 28) -> None:
        target.scroll_into_view_if_needed()
        box = target.bounding_box()
        if box is None:
            raise DemoError(f"Элемент не виден: {target}")
        x, y = box["x"] + box["width"] / 2, box["y"] + min(box["height"] / 2, 22)
        self.page.mouse.move(x, y, steps=steps)
        self.x, self.y = x, y

    def click(self, target: Locator, *, wait: float = 0.35) -> None:
        self.move(target)
        self.pause(0.18)
        target.click()
        self.pause(wait)

    def caption(self, text: str, sub: str = "") -> None:
        self.page.evaluate("([t, s]) => window.__demo.caption(t, s)", [text, sub])

    def hide_caption(self) -> None:
        self.page.evaluate("window.__demo.hideCaption()")

    def card(self, kicker: str, title: str, subtitle: str = "") -> None:
        self.page.evaluate("([k, t, s]) => window.__demo.card(k, t, s)", [kicker, title, subtitle])

    def hide_card(self) -> None:
        self.page.evaluate("window.__demo.hideCard()")

    def scroll(self, dy: int, *, steps: int = 12) -> None:
        for _ in range(steps):
            self.page.mouse.wheel(0, dy / steps)
            self.page.wait_for_timeout(35)


