def record(tokens: dict, headed: bool, voice_durations: dict[str, float]) -> tuple[Path, float, dict[str, float], float]:
    OUT.mkdir(parents=True, exist_ok=True)
    raw_dir = Path(tempfile.mkdtemp(prefix="okurmen-demo-"))
    with sync_playwright() as pw:
        browser = pw.chromium.launch(headless=not headed)
        context = browser.new_context(
            viewport=VIEWPORT, device_scale_factor=SCALE, locale="ru-RU", timezone_id="Asia/Bishkek",
            record_video_dir=str(raw_dir), record_video_size=VIDEO_SIZE, accept_downloads=True,
        )
        context.grant_permissions(["clipboard-read", "clipboard-write"], origin=FRONTEND)
        context.add_init_script(
            f"localStorage.setItem('okurmenkids.access_token', {json.dumps(tokens['access'])});"
            f"localStorage.setItem('okurmenkids.refresh_token', {json.dumps(tokens['refresh'])});"
        )
        context.add_init_script(OVERLAY_JS)
