# ---------------------------------------------------------------------------
# Preflight (API) — verifies the feature works before anything is recorded.
# ---------------------------------------------------------------------------

def _request(method: str, path: str, *, token: str | None = None, body: dict | None = None, raw: bool = False):
    url = path if path.startswith("http") else f"{API}{path}"
    data = json.dumps(body).encode() if body is not None else None
    request = urllib.request.Request(url, data=data, method=method)
    request.add_header("Content-Type", "application/json")
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request, timeout=120) as response:
            payload = response.read()
            return payload if raw else json.loads(payload or b"null")
    except urllib.error.HTTPError as exc:
        raise DemoError(f"{method} {url} → HTTP {exc.code}: {exc.read()[:300]!r}") from exc
    except urllib.error.URLError as exc:
        raise DemoError(f"{method} {url} недоступен: {exc.reason}") from exc


def check(condition: bool, message: str) -> None:
    if not condition:
        raise DemoError(message)
    print(f"  ✓ {message}")


def preflight(password: str) -> dict:
    print("Preflight:")
    try:
        with urllib.request.urlopen(FRONTEND, timeout=15) as response:
            check(response.status == 200, f"frontend отвечает ({FRONTEND})")
    except urllib.error.URLError as exc:
        raise DemoError(f"frontend недоступен ({FRONTEND}): {exc.reason}") from exc

    tokens = _request("POST", "/auth/login/", body={"username": USERNAME, "password": password})
    check(bool(tokens.get("access")), f"backend отвечает, вход {USERNAME} выполнен ({API})")
    token = tokens["access"]

    groups = _request("GET", f"/groups/?search={urllib.parse.quote(GROUP_NAME)}", token=token)
    group = next((g for g in groups.get("results", []) if g["name"] == GROUP_NAME), None)
    check(group is not None, f"демо-группа «{GROUP_NAME}» доступна тренеру")

    base = {"period": "last_month", "output_format": "both", "include_table": True, "include_group_stats": True,
            "include_recommendations": True, "include_comparison": True}
    report = _request("POST", f"/groups/{group['id']}/parent-reports/generate/", token=token,
                      body={**base, "report_type": "group", "language": "ru"})
    check(report["status"] == "ready" and report["images"], "отчёт по группе сгенерирован, PNG создан")
    stats = report["snapshot"]["group_stats"]
    check(stats["conducted_lessons"] > 0 and stats["attendance_rate"] is not None,
          f"статистика посчитана: {stats['conducted_lessons']} занятий, посещаемость {stats['attendance_rate']}%")

    png = _request("GET", f"/parent-reports/{report['id']}/download/?image={report['images'][0]['id']}", token=token, raw=True)
    check(png[:8] == b"\x89PNG\r\n\x1a\n" and len(png) > 50_000, f"PNG скачивается ({len(png) // 1024} КБ)")

    check(report["text"].startswith("Уважаемые родители"), "текст для WhatsApp (RU) сформирован")
    kyrgyz = _request("POST", f"/parent-reports/{report['id']}/text/", token=token, body={"language": "ky"})
    check(kyrgyz["text"].startswith("Саламатсыздарбы"), "переключение языка RU → KY работает")

    # A second, earlier report so «История отчётов» has more than the one made on camera.
    individual = _request("POST", f"/groups/{group['id']}/parent-reports/generate/", token=token,
                          body={**base, "report_type": "students", "language": "ky"})
    check(individual["status"] == "ready" and len(individual["images"]) == len(individual["snapshot"]["students"]),
          f"индивидуальные отчёты (KY): {len(individual['images'])} PNG")
    return {"tokens": tokens, "group": group}


