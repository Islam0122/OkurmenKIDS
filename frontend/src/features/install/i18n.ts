export const INSTALL_TEXT: Record<InstallLang, InstallText> = { ru, kg }

function initialLang(): InstallLang {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY)
    if (saved === 'kg' || saved === 'ru') return saved
  } catch {
    /* storage unavailable */
  }
  const browser = (typeof navigator !== 'undefined' ? navigator.language : '').toLowerCase()
  return browser.startsWith('ky') ? 'kg' : 'ru'
}

export function useInstallLang(): { lang: InstallLang; t: InstallText; setLang: (lang: InstallLang) => void } {
  const [lang, setLangState] = useState<InstallLang>(initialLang)
  useEffect(() => {
    document.documentElement.lang = lang === 'kg' ? 'ky' : 'ru'
  }, [lang])
  const setLang = useCallback((next: InstallLang) => {
    setLangState(next)
    try {
      window.localStorage.setItem(STORAGE_KEY, next)
    } catch {
      /* the choice just lasts for this visit */
    }
  }, [])
  return { lang, t: INSTALL_TEXT[lang], setLang }
}
