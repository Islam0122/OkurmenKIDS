"""Сервисный слой оплаты обучения. Представления, сериализаторы, сигналы и
Celery-задачи только вызывают эти функции; вся бизнес-логика — здесь.

Каждая финансовая операция выполняется в `transaction.atomic()` под
блокировкой платёжного профиля (`select_for_update`), поэтому операции
одного студента выполняются строго по очереди, а уникальные ограничения БД
— последняя защита от дублей при повторных запусках."""


class BillingError(Exception):
    """Нарушение бизнес-правила оплаты — показывается пользователю как 400."""

    def __init__(self, message: str, *, code: str = "invalid"):
        super().__init__(message)
        self.message = message
        self.code = code
